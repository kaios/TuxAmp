TEXT_H = 6

_cache = {}


def _glyph(ch):
    g = _G.get(ch)
    if g is None:
        # strip common accents to their base letter, otherwise show '?'
        import unicodedata
        base = unicodedata.normalize("NFKD", ch)[:1]
        g = _G.get(base.upper()) if base else None
        if g is None:
            g = _G["?"]
    return g


def text_width(s):
    w = 0
    for ch in s.upper():
        w += len(_glyph(ch)[0]) + 1
    return w


def render_text(s, color, bg=None):
    """Render string with the 5px pixel font; returns a Surface 6px tall."""
    key = (s, color, bg)
    surf = _cache.get(key)
    if surf is not None:
        return surf
    s_up = s.upper()
    w = max(1, text_width(s_up))
    surf = pygame.Surface((w, TEXT_H), pygame.SRCALPHA)
    if bg is not None:
        surf.fill(bg)
    x = 0
    for ch in s_up:
        g = _glyph(ch)
        for gy, row in enumerate(g):
            for gx, c in enumerate(row):
                if c == "#":
                    surf.set_at((x + gx, gy), color)
        x += len(g[0]) + 1
    if len(_cache) > 512:
        _cache.clear()
    _cache[key] = surf
    return surf


# 7-segment style big digits, 9x13, segments: a top, b upper-right,
# c lower-right, d bottom, e lower-left, f upper-left, g middle
_SEG = {
    "0": "abcdef", "1": "bc", "2": "abged", "3": "abgcd", "4": "fgbc",
    "5": "afgcd", "6": "afgedc", "7": "abc", "8": "abcdefg", "9": "abcdfg",
    "-": "g", " ": "",
}


def draw_big_digit(surf, x, y, ch, color, shadow=None):
    segs = _SEG.get(ch, "")
    rects = {
        "a": (x + 2, y, 5, 2),
        "b": (x + 7, y + 1, 2, 5),
        "c": (x + 7, y + 7, 2, 5),
        "d": (x + 2, y + 11, 5, 2),
        "e": (x, y + 7, 2, 5),
        "f": (x, y + 1, 2, 5),
        "g": (x + 2, y + 5, 5, 2),
    }
    for k, r in rects.items():
        if k in segs:
            surf.fill(color, r)
        elif shadow is not None:
            surf.fill(shadow, r)
